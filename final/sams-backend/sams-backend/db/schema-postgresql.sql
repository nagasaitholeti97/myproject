-- SAMS schema for PostgreSQL 12 or newer.
--
-- You do not have to run this file: with the "postgres" profile Hibernate creates the same tables for you.
-- Use it when you want to set the database up yourself (then start the app with DDL_AUTO=validate).
--
-- 1. Create the database once, from the shell:        createdb -U postgres sams
-- 2. Load this file:                                  psql -U postgres -d sams -f db/schema-postgresql.sql

CREATE TABLE IF NOT EXISTS section (
    id          VARCHAR(255) PRIMARY KEY,
    name        VARCHAR(255),
    study_year  INTEGER NOT NULL,
    department  VARCHAR(255),
    course      VARCHAR(255),
    id_prefix   VARCHAR(255)          -- start of the student IDs of the class, e.g. 24ECE3
);

CREATE TABLE IF NOT EXISTS subject (
    id    VARCHAR(255) PRIMARY KEY,
    code  VARCHAR(255),
    name  VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS student (
    id             VARCHAR(255) PRIMARY KEY,
    name           VARCHAR(255),
    gender         VARCHAR(255),
    date_of_birth  DATE,
    phone          VARCHAR(255),
    email          VARCHAR(255),
    father_name    VARCHAR(255),
    mother_name    VARCHAR(255),
    address        VARCHAR(255),
    city           VARCHAR(255),
    pincode        VARCHAR(255),
    department     VARCHAR(255),
    course         VARCHAR(255),
    section_id     VARCHAR(255) NOT NULL REFERENCES section (id)
);

CREATE TABLE IF NOT EXISTS faculty (
    id             VARCHAR(255) PRIMARY KEY,
    name           VARCHAR(255),
    gender         VARCHAR(255),
    age            INTEGER,
    designation    VARCHAR(255),
    qualification  VARCHAR(255),
    experience     INTEGER,
    department     VARCHAR(255),
    phone          VARCHAR(255),
    email          VARCHAR(255),
    subject_id     VARCHAR(255) NOT NULL REFERENCES subject (id)   -- the one subject this faculty member teaches
);

-- One login table for both roles. user_id is the student ID or the faculty ID.
CREATE TABLE IF NOT EXISTS user_account (
    user_id        VARCHAR(255) PRIMARY KEY,
    role           VARCHAR(255) CHECK (role IN ('STUDENT', 'FACULTY')),
    password_hash  VARCHAR(255)       -- BCrypt hash, never the password itself
);

CREATE TABLE IF NOT EXISTS academic_event (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(255),
    title          VARCHAR(255),
    type           VARCHAR(255) CHECK (type IN ('SEMESTER', 'CLASS_TEST', 'ASSIGNMENT', 'EXAM', 'HOLIDAY', 'EVENT')),
    start_date     DATE,
    end_date       DATE,
    academic_year  VARCHAR(255),
    subject_id     VARCHAR(255) REFERENCES subject (id)
);

-- One row per student, subject and day. period is the hour of the day, 0 to 4.
CREATE TABLE IF NOT EXISTS attendance (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id  VARCHAR(255) NOT NULL REFERENCES student (id),
    subject_id  VARCHAR(255) NOT NULL REFERENCES subject (id),
    section_id  VARCHAR(255) NOT NULL REFERENCES section (id),
    faculty_id  VARCHAR(255) NOT NULL REFERENCES faculty (id),
    class_date  DATE,
    period      INTEGER NOT NULL,
    status      VARCHAR(255) CHECK (status IN ('PRESENT', 'ABSENT')),
    CONSTRAINT uk_attendance_student_subject_day UNIQUE (student_id, subject_id, class_date)
);

CREATE INDEX IF NOT EXISTS idx_attendance_student ON attendance (student_id);
CREATE INDEX IF NOT EXISTS idx_attendance_class   ON attendance (section_id, subject_id, class_date);
CREATE INDEX IF NOT EXISTS idx_student_section    ON student (section_id);
